//! Compiles external Rust modules placed in `modules/*.rs`.
//!
//! Every file must expose `pub struct Module` implementing
//! `crate::module::Module`. The build script declares each file as a module of
//! the crate and registers it through `inventory`, so external modules have
//! the same API and performance as built-in ones.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("manifest dir"));
    let modules = manifest.join("modules");
    let _ = std::fs::create_dir_all(&modules);
    println!("cargo:rerun-if-changed={}", modules.display());

    let mut files = Vec::new();
    if let Ok(entries) = std::fs::read_dir(&modules) {
        for entry in entries.flatten() {
            let path = entry.path();
            if path.extension().and_then(|ext| ext.to_str()) != Some("rs") {
                continue;
            }
            println!("cargo:rerun-if-changed={}", path.display());
            files.push(path);
        }
    }
    files.sort();

    let mut out = String::from("// @generated by build.rs — do not edit.\n");
    for path in files {
        let Some(stem) = path.file_stem().and_then(|stem| stem.to_str()) else {
            continue;
        };
        let ident = identifier(stem);
        let path = path.to_string_lossy();
        let _ = writeln!(out, "#[path = r#\"{path}\"#]");
        let _ = writeln!(out, "pub mod ext_{ident};");
        let _ = writeln!(
            out,
            "::inventory::submit! {{\n    crate::module::ModuleFactory(|| Box::new(ext_{ident}::Module))\n}}"
        );
    }

    let dest = Path::new(&std::env::var("OUT_DIR").expect("out dir")).join("external_modules.rs");
    std::fs::write(&dest, out).expect("write external modules registry");
}

/// Turn a file stem into a valid, collision-free Rust identifier.
fn identifier(stem: &str) -> String {
    let mut out = String::with_capacity(stem.len() + 2);
    for ch in stem.chars() {
        if ch.is_ascii_alphanumeric() {
            out.push(ch.to_ascii_lowercase());
        } else {
            out.push('_');
        }
    }
    if out.is_empty() || out.starts_with(|ch: char| ch.is_ascii_digit()) {
        out.insert_str(0, "m_");
    }
    out
}
